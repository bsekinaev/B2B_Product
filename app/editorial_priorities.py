"""Ранжирование только предоставленных технических полей для редакторской подачи.

Не выводит свойств из названия модели и не изменяет значения характеристик.
"""

from collections.abc import Mapping

# Уровни по смыслу для измерительных приборов: канал/вход/выход раньше
# питания, интерфейса и вторичных эксплуатационных характеристик.
_CONTROLLER_TIERS: tuple[tuple[str, ...], ...] = (
    (
        "количество универсальных измерительных входов",
        "количество универсальных входов",
        "количество основных измерительных входов",
        "количество измерительных каналов",
        "количество измерительных входов",
        "количество входов датчиков",
        "количество входов для датчиков",
        "количество каналов",
        "количество входов",
    ),
    (
        "входные сигналы",
        "поддерживаемые датчики",
        "дополнительный вход",
    ),
    (
        "типы выходных устройств",
        "выходные устройства",
        "выходные элементы",
        "выходные сигналы",
    ),
    (
        "количество выходных устройств",
        "количество выходных элементов",
        "количество выходов",
        "сигнализация",
    ),
    (
        "программы",
        "алгоритм регулирования",
        "режимы управления",
        "исполнения корпуса",
    ),
    ("интерфейс", "протокол связи"),
    ("напряжение питания", "погрешност"),
    ("время опроса", "время измерения", "частота питания", "потребляемая мощность"),
)

_EXCLUDED = frozenset({"тип", "серия", "статус исполнения"})


def ranked_spec_names(
    specs: Mapping[str, str],
    category: str,
    limit: int,
    max_name_len: int = 45,
) -> list[str]:
    """Возвращает исходные ключи, без значений и домыслов, в порядке полезности.

    Для остальных категорий действуют собственные приоритеты генератора.
    Слишком длинные поля не используются в вводных и поисковых запросах,
    но остаются без изменений в полном техническом описании.
    """
    if category != "controller" or limit <= 0:
        return []

    candidates = [
        key
        for key, value in specs.items()
        if key.casefold() not in _EXCLUDED and value.strip() and len(key) <= max_name_len
    ]

    def priority(key: str) -> tuple[int, int]:
        normalized = key.casefold()
        for tier_index, terms in enumerate(_CONTROLLER_TIERS):
            if any(term in normalized for term in terms):
                return tier_index, candidates.index(key)
        return len(_CONTROLLER_TIERS), candidates.index(key)

    return sorted(candidates, key=priority)[:limit]
