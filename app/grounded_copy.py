"""Консервативный текст по исходным характеристикам без рекламных обещаний.

Используется только как резервная редакторская стратегия при неуспешной
LLM-генерации. Это шаблонный черновик для проверки человеком, не паспорт товара.
"""

import re

from app.schemas import ProductInput

_UNTRUSTED_INSTRUCTION = re.compile(
    r"игнорир|системн\w* промпт|забудь|инструкци\w* выше|выполни команд", re.I
)


def _description_fact(product: ProductInput) -> str:
    """Включить лишь короткое исходное описание, без явных инструкций к LLM."""
    raw = (product.description or "").split("Демонстрационные данные", 1)[0].strip().rstrip(". ")
    if not raw or len(raw) > 400 or _UNTRUSTED_INSTRUCTION.search(raw):
        return ""
    return f" Согласно предоставленному описанию: {raw}."


def _selection_context(key: str) -> str:
    name = key.casefold()
    if "диапазон" in name:
        return (
            "Этот параметр сверяют с необходимой областью измерений; "
            "одного диапазона недостаточно для подтверждения пригодности прибора "
            "к конкретному технологическому процессу."
        )
    if "точност" in name:
        return (
            "При подборе его сопоставляют с требованиями к точности "
            "и технической документацией задачи; указанное значение "
            "само по себе не заменяет проверку применимости."
        )
    if "присоедин" in name:
        return (
            "Перед заказом необходимо сопоставить присоединение с параметрами "
            "монтажного узла и его документацией, не предполагая совместимость "
            "только по наименованию модели."
        )
    if "диаметр" in name or "корпус" in name:
        return (
            "При подборе следует сверить указанный габарит с требованиями "
            "к монтажу и имеющемуся пространству по проектной документации."
        )
    if "погружн" in name or "длина" in name:
        return (
            "При выборе исполнения сверяют этот размер с монтажными требованиями "
            "и технической документацией оборудования."
        )
    if "тип" in name:
        return (
            "Характеристика позволяет различать варианты исполнения; "
            "пригодность для конкретных условий требует подтверждения по паспорту."
        )
    return (
        "Значение необходимо сверить с требованиями заказчика "
        "и технической документацией изделия до оформления заказа."
    )


def grounded_seo_description(product: ProductInput) -> str | None:
    """Собрать 800–1200 содержательных символов либо отказаться от результата.

    Не повторяет фразы циклом, не изменяет характеристики и не отрезает
    предложение посередине. При недостатке фактов возвращает None.
    """
    filled = [(key, value) for key, value in product.specs.items() if value]
    if len(filled) < 3:
        return None

    intro = (
        f"{product.name} — позиция каталога производителя «{product.manufacturer}»."
        f"{_description_fact(product)} "
        "Ниже представлены параметры из исходных данных, которые следует "
        "сопоставить с требованиями к закупке."
    )
    details = " ".join(
        f"Для характеристики «{key}» указано значение «{value}». {_selection_context(key)}"
        for key, value in filled
    )
    closing = (
        "Карточка позволяет предварительно сравнить заявленные значения, "
        "но не подтверждает дополнительные свойства товара. "
        "Перед заказом рекомендуется уточнить недостающие сведения "
        "по паспорту изделия и согласовать необходимые параметры с поставщиком."
    )
    optional = (
        "Проверка характеристик по исходному техническому документу "
        "важна перед включением товара в заявку: приведённые сведения "
        "не являются подтверждением пригодности для условий эксплуатации."
    )
    sections = [intro, details, closing]
    candidate = "\n\n".join(sections)
    if len(candidate) > 1200:
        sections.pop()
        candidate = "\n\n".join(sections)
    if len(candidate) < 800:
        sections.append(optional)
        candidate = "\n\n".join(sections)
    return candidate if 800 <= len(candidate) <= 1200 else None


def grounded_commercial_note(product: ProductInput) -> str:
    """Назвать аудиторию подбора, не приписывая прибору неподтверждённые свойства."""
    return (
        f"Для специалистов по закупкам и подбору оборудования: «{product.name}» "
        "можно рассматривать при сравнении указанных в карточке параметров "
        "с требованиями заявки. Пригодность для конкретной задачи следует "
        "подтвердить по техническому паспорту; дополнительные сведения уточнить у поставщика."
    )
